/* ==========================================================================
   withHttpsOnly.js - Expo config plugin
   ICT6400 Assessment 4 - CareerHub mobile

   The android/ folder is generated by "expo prebuild", so a manual edit there
   would be lost. This plugin makes the HTTPS rule part of every build:
     1. it writes res/xml/network_security_config.xml, which refuses cleartext
        traffic for every domain, and
     2. it points AndroidManifest.xml at that file and turns off
        usesCleartextTraffic.
   With this in place Android itself blocks any http:// request from the app.
   ========================================================================== */

const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <!-- No domain may use http://. Only the system certificate store is trusted. -->
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withSecurityConfigFile(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const xmlDir = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app/src/main/res/xml'
      );
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(xmlDir, 'network_security_config.xml'),
        NETWORK_SECURITY_CONFIG
      );
      return modConfig;
    },
  ]);
}

function withSecurityManifest(config) {
  return withAndroidManifest(config, (modConfig) => {
    const application = modConfig.modResults.manifest.application[0];
    application.$['android:usesCleartextTraffic'] = 'false';
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return modConfig;
  });
}

module.exports = function withHttpsOnly(config) {
  return withSecurityManifest(withSecurityConfigFile(config));
};
